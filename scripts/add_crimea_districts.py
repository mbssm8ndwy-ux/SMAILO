def main() -> None:
    conn = sqlite3.connect("shop.db")
    cur = conn.cursor()
    cities_added = 0
    districts_added = 0
    for city_name, districts in CITY_DISTRICTS.items():
        cur.execute("INSERT OR IGNORE INTO cities(name) VALUES (?)", (city_name,))
        if cur.rowcount > 0:
            cities_added += 1
        city_id = cur.execute(
            "SELECT id FROM cities WHERE name = ?",
            (city_name,),
        ).fetchone()[0]
        for dname in districts:
            cur.execute(
                "INSERT OR IGNORE INTO districts(city_id, name) VALUES (?, ?)",
                (city_id, dname),
            )
            if cur.rowcount > 0:
                districts_added += 1
    conn.commit()
    conn.close()
    print(f"cities_added={cities_added}")
    print(f"districts_added={districts_added}")


if __name__ == "__main__":
    main()

